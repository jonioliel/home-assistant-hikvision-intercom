import {chromium} from '../../../frontend/node_modules/@playwright/test/index.mjs';
import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.dirname(fileURLToPath(import.meta.url));
const base=process.env.WISKEY_DESIGN_URL||'http://127.0.0.1:8788/v3/';
const browser=await chromium.launch({headless:true,executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const page=await browser.newPage({viewport:{width:1440,height:900}});
const errors=[],failedResources=[];
page.on('pageerror',e=>errors.push(String(e)));
page.on('response',r=>{if(r.status()>=400&&!r.url().endsWith('favicon.ico'))failedResources.push({url:r.url(),status:r.status()});});
await page.goto(`${base}index.html?freeze=1#people`);await page.evaluate(()=>document.fonts.ready);
const peopleRows=await page.locator('tr[data-person-row]').count();
await page.locator('tr[data-person-row="1"]').click();
const selection=(await page.locator('.inspector').innerText()).includes('איתי רז');
const fontLoaded=await page.evaluate(()=>document.fonts.check('14px Heebo'));
await page.goto(`${base}gallery.html`);const gallery=await page.locator('.screen-card').count();
await page.setViewportSize({width:1800,height:1200});
await page.goto(`${base}comparison.html`);await page.evaluate(()=>document.fonts.ready);
await page.screenshot({path:path.join(root,'images/comparison.png'),fullPage:true});
await page.screenshot({path:path.join(process.env.TEMP,'wiskey-v3-comparison.jpg'),type:'jpeg',quality:70,fullPage:true});
const report={generatedAt:new Date().toISOString(),base,errors,failedResources,peopleRows,selection,fontLoaded,gallery};
await fs.writeFile(path.join(root,'PREVIEW_VALIDATION.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report,null,2));await browser.close();
if(errors.length||failedResources.length||peopleRows!==12||!selection||!fontLoaded||gallery!==12)process.exitCode=1;
